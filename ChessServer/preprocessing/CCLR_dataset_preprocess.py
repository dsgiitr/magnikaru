import chess.pgn

input_path = "/content/drive/MyDrive/magnikaru/games.pgn"
output_path = "/content/drive/MyDrive/magnikaru/filtered_games.pgn"

filtered_games = 0
total_games = 0

with open(input_path, "r", encoding="latin1", errors="ignore") as in_file, \
     open(output_path, "w", encoding="latin1") as out_file:

    while True:
        game = chess.pgn.read_game(in_file)
        if game is None:
            break  # End of file

        total_games += 1
        # print("game: ", total_games)
        # ELO difference check
        try:
            w_elo = int(game.headers.get("WhiteElo"))
            b_elo = int(game.headers.get("BlackElo"))
            if abs(w_elo - b_elo) > 150:
                continue
        except:
            continue

        # skip draws
        result = game.headers.get("Result")
        if result not in ["1-0", "0-1"]:
            continue


        out_file.write(str(game) + "\n\n")
        filtered_games += 1
        # print("Filtered: ", filtered_games)

print(f"Done. Total games scanned: {total_games}")
print(f"Filtered games written: {filtered_games}")